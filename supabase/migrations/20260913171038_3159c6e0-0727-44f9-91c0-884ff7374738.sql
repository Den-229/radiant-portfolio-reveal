CREATE TYPE public.app_role AS ENUM ('admin', 'user');

CREATE TABLE public.portfolio_profile (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  name text NOT NULL,
  role text NOT NULL,
  tagline text NOT NULL,
  location text NOT NULL,
  email text NOT NULL,
  linkedin text NOT NULL DEFAULT '',
  github text NOT NULL DEFAULT '',
  availability text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.portfolio_profile TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.portfolio_profile TO authenticated;
GRANT ALL ON public.portfolio_profile TO service_role;
ALTER TABLE public.portfolio_profile ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.portfolio_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('project','experience','skill','education','testimonial')),
  title text NOT NULL,
  subtitle text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  period text NOT NULL DEFAULT '',
  link text NOT NULL DEFAULT '',
  featured boolean NOT NULL DEFAULT false,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.portfolio_entries TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.portfolio_entries TO authenticated;
GRANT ALL ON public.portfolio_entries TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.portfolio_entries_id_seq TO authenticated, service_role;
ALTER TABLE public.portfolio_entries ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.user_roles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  role public.app_role NOT NULL,
  UNIQUE (user_id, role)
);
GRANT SELECT ON public.user_roles TO authenticated;
GRANT ALL ON public.user_roles TO service_role;
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.has_role(_user_id uuid, _role public.app_role)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_roles
    WHERE user_id = _user_id AND role = _role
  )
$$;

CREATE POLICY "Public can view portfolio profile"
ON public.portfolio_profile FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admins can manage portfolio profile"
ON public.portfolio_profile FOR ALL TO authenticated
USING (public.has_role(auth.uid(), 'admin'))
WITH CHECK (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Public can view portfolio entries"
ON public.portfolio_entries FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admins can manage portfolio entries"
ON public.portfolio_entries FOR ALL TO authenticated
USING (public.has_role(auth.uid(), 'admin'))
WITH CHECK (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Users can view their own roles"
ON public.user_roles FOR SELECT TO authenticated
USING (user_id = auth.uid());

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$;
CREATE TRIGGER portfolio_profile_updated_at BEFORE UPDATE ON public.portfolio_profile FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER portfolio_entries_updated_at BEFORE UPDATE ON public.portfolio_entries FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

